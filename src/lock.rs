use anyhow::Result;
use argon2::{Argon2, PasswordHasher, PasswordVerifier};

pub const MIN_PASSWORD_LENGTH: usize = 6;

pub fn hash_password(password: &str) -> Result<String> {
    Argon2::default()
        .hash_password(password.as_bytes())
        .map(|hash| hash.to_string())
        .map_err(|error| anyhow::anyhow!("could not hash the password: {error}"))
}

pub fn verify_password(hash: &str, password: &str) -> bool {
    Argon2::default()
        .verify_password(password.as_bytes(), hash)
        .is_ok()
}

pub fn validate_password(password: &str) -> Result<(), String> {
    if password.chars().count() < MIN_PASSWORD_LENGTH {
        return Err(format!("Use at least {MIN_PASSWORD_LENGTH} characters."));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hashes_and_verifies_a_password() {
        let hash = hash_password("correct horse battery staple").unwrap();
        assert!(hash.starts_with("$argon2"));
        assert!(verify_password(&hash, "correct horse battery staple"));
        assert!(!verify_password(&hash, "wrong password"));
    }

    #[test]
    fn verifies_a_hash_created_with_argon2_0_5() {
        // Fixture generated by argon2 0.5.3 with its default Argon2id
        // parameters. Stored application locks must keep verifying after
        // the password-hash 0.6 migration.
        let legacy = "$argon2id$v=19$m=19456,t=2,p=1$oAxUl0dIBlQeDRhhQ5gQ4w$yQ7zLt3lqQHAJBST4Z0NHreg24nc1YKBXtag6p8k0e4";
        assert!(verify_password(legacy, "correct horse battery staple"));
        assert!(!verify_password(legacy, "wrong password"));
    }

    #[test]
    fn rejects_malformed_hashes() {
        assert!(!verify_password("not-a-hash", "anything"));
        assert!(!verify_password("", ""));
    }

    #[test]
    fn validates_password_length() {
        assert!(validate_password("12345").is_err());
        assert!(validate_password("123456").is_ok());
    }
}
